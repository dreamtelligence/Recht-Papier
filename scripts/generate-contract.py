"""Generate client types from the server's JSON Schema; --check detects drift."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "packages/shared"


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    kind = schema["type"]
    if kind == "object":
        required = schema.get("required", [])
        return "{\n" + "\n".join(
            f"  {key}{'' if key in required else '?'}: {ts(value)};"
            for key, value in schema["properties"].items()
        ) + "\n}"
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}[kind]


schema = json.loads((ROOT / "contract.schema.json").read_text())
output = "// Generated by scripts/generate-contract.py. Edit contract.schema.json.\n\n"
output += "\n\n".join(f"export type {name} = {ts(value)};" for name, value in schema["definitions"].items()) + "\n"
target = ROOT / "contract.ts"
if "--check" in sys.argv:
    assert target.read_text() == output, "Contract types are stale"
else:
    target.write_text(output)
